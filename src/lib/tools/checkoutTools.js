import { tool } from "@langchain/core/tools";
import { z } from "zod";

import prisma from "@/lib/db/prisma";

import {
  evaluateTransaction,
} from "@/lib/policy/policyEngine";

import {
  getDailySpent,
} from "@/lib/policy/spending";

import {
  recordAgentAction,
} from "@/lib/audit/auditLog";

/**
 * Create a checkout tool bound to one authenticated buyer.
 *
 * Security:
 * - userId comes from the authenticated Auth.js session.
 * - Gemini only supplies cartId.
 * - Cart ownership is checked on the server.
 * - Product prices and inventory come from PostgreSQL.
 * - Daily spending comes from PostgreSQL.
 * - Policy evaluation is deterministic.
 * - The exact policy result is persisted on Checkout.
 * - The checkout amount is generated by the backend.
 */
export function createCheckoutTool(userId) {
  if (!userId) {
    throw new Error(
      "userId is required to create checkout tool"
    );
  }

  return tool(
    async ({ cartId } = {}) => {
      try {
        /*
         * --------------------------------------------------
         * 1. Fetch this authenticated buyer's cart.
         * If cartId is provided, look it up directly.
         * If omitted, automatically resolve the active cart.
         * --------------------------------------------------
         */
        const trimmedCartId = cartId?.trim();

        const cart = trimmedCartId
          ? await prisma.cart.findFirst({
              where: {
                id: trimmedCartId,
                userId,
              },
              include: {
                items: {
                  include: {
                    product: true,
                  },
                },
              },
            })
          : await prisma.cart.findFirst({
              where: {
                userId,
                status: "ACTIVE",
              },
              include: {
                items: {
                  include: {
                    product: true,
                  },
                },
              },
              orderBy: {
                createdAt: "desc",
              },
            });

        if (!cart) {
          return JSON.stringify({
            success: false,
            checkoutCreated: false,
            error: trimmedCartId ? "Cart not found" : "No active cart found for this account",
          });
        }

        /*
         * --------------------------------------------------
         * 2. Validate cart state.
         * --------------------------------------------------
         */
        if (cart.status !== "ACTIVE") {
          return JSON.stringify({
            success: false,
            checkoutCreated: false,
            error: "Cart is not active",
          });
        }

        if (!cart.items.length) {
          return JSON.stringify({
            success: false,
            checkoutCreated: false,
            error: "Cart is empty",
          });
        }

        /*
         * --------------------------------------------------
         * 3. Recalculate authoritative amount from DB.
         * --------------------------------------------------
         */
        let totalAmount = 0;

        const items = [];

        for (const item of cart.items) {
          /*
           * Product must exist.
           */
          if (!item.product) {
            await recordAgentAction({
              agentType: "BUYER_AGENT",
              action: "CHECKOUT_BLOCKED",
              entityType: "Cart",
              entityId: cart.id,

              input: {
                userId,
                cartId: cart.id,
                productId: item.productId,
              },

              status: "BLOCKED",

              reason:
                "A product in the cart no longer exists",
            });

            return JSON.stringify({
              success: false,
              checkoutCreated: false,
              error:
                "A product in the cart no longer exists",
            });
          }

          /*
           * Product must still be active.
           */
          if (!item.product.active) {
            await recordAgentAction({
              agentType: "BUYER_AGENT",
              action: "CHECKOUT_BLOCKED",
              entityType: "Cart",
              entityId: cart.id,

              input: {
                userId,
                cartId: cart.id,
                productId: item.product.id,
              },

              status: "BLOCKED",

              reason:
                `${item.product.name} is no longer available`,
            });

            return JSON.stringify({
              success: false,
              checkoutCreated: false,
              error:
                `${item.product.name} is no longer available`,
            });
          }

          /*
           * Quantity must be valid.
           */
          if (
            !Number.isInteger(item.quantity) ||
            item.quantity <= 0
          ) {
            await recordAgentAction({
              agentType: "BUYER_AGENT",
              action: "CHECKOUT_BLOCKED",
              entityType: "Cart",
              entityId: cart.id,

              input: {
                userId,
                cartId: cart.id,
                productId: item.product.id,
                quantity: item.quantity,
              },

              status: "BLOCKED",

              reason:
                "Invalid cart quantity",
            });

            return JSON.stringify({
              success: false,
              checkoutCreated: false,
              error:
                `Invalid quantity for ${item.product.name}`,
            });
          }

          /*
           * Inventory check at checkout time.
           */
          if (
            item.product.inventory <
            item.quantity
          ) {
            await recordAgentAction({
              agentType: "BUYER_AGENT",
              action: "CHECKOUT_BLOCKED",
              entityType: "Cart",
              entityId: cart.id,

              input: {
                userId,
                cartId: cart.id,
                productId: item.product.id,
                requestedQuantity:
                  item.quantity,
                availableInventory:
                  item.product.inventory,
              },

              status: "BLOCKED",

              reason:
                `Insufficient inventory for ${item.product.name}`,
            });

            return JSON.stringify({
              success: false,
              checkoutCreated: false,
              error:
                `Insufficient inventory for ${item.product.name}`,
            });
          }

          /*
           * Price comes only from PostgreSQL.
           */
          const subtotal =
            item.product.price *
            item.quantity;

          totalAmount += subtotal;

          items.push({
            productId:
              item.product.id,

            name:
              item.product.name,

            quantity:
              item.quantity,

            unitPrice:
              item.product.price,

            subtotal,
          });
        }

        /*
         * --------------------------------------------------
         * 4. Calculate real daily spending.
         * --------------------------------------------------
         */
        const dailySpent =
          await getDailySpent(userId);

        /*
         * --------------------------------------------------
         * 5. Current checkout discount.
         *
         * No discount is silently invented here.
         * Future offers must come from authoritative
         * backend campaign/offer data.
         * --------------------------------------------------
         */
        const discountPercent = 0;

        /*
         * --------------------------------------------------
         * 6. Deterministic policy evaluation.
         * --------------------------------------------------
         */
        const policy =
          evaluateTransaction({
            amount:
              totalAmount,

            dailySpent,

            discountPercent,
          });

        /*
         * --------------------------------------------------
         * 7. Persist the policy decision in the audit log.
         * --------------------------------------------------
         */
        await recordAgentAction({
          agentType: "BUYER_AGENT",
          action: "POLICY_EVALUATED",
          entityType: "Cart",
          entityId: cart.id,

          input: {
            userId,
            cartId: cart.id,
            amount: totalAmount,
            dailySpent,
            discountPercent,
          },

          output: policy,

          status:
            policy.status ===
            "APPROVAL_REQUIRED"
              ? "WAITING"
              : policy.status,

          reason:
            policy.reason,
        });

        /*
         * --------------------------------------------------
         * 8. Stop immediately when policy blocks.
         * --------------------------------------------------
         */
        if (
          policy.status === "BLOCKED"
        ) {
          return JSON.stringify({
            success: false,

            checkoutCreated:
              false,

            policy,

            amount:
              totalAmount,

            currency:
              "INR",

            dailySpent,

            items,
          });
        }

        /*
         * --------------------------------------------------
         * 9. Reuse an unfinished checkout when possible.
         *
         * This prevents duplicate checkout records when
         * the same buyer repeats a request.
         * --------------------------------------------------
         */
        const existingCheckout =
          await prisma.checkout.findFirst({
            where: {
              cartId: cart.id,

              status: {
                in: [
                  "READY",
                  "AWAITING_APPROVAL",
                  "APPROVED",
                  "PAYMENT_PENDING",
                  "PAYMENT_VERIFIED",
                ],
              },
            },

            orderBy: {
              createdAt: "desc",
            },
          });

        if (existingCheckout) {
          /*
           * Only reuse if the amount still matches.
           */
          if (
            existingCheckout.amount ===
            totalAmount
          ) {
            await recordAgentAction({
              agentType: "BUYER_AGENT",
              action: "CHECKOUT_REUSED",
              entityType: "Checkout",
              entityId:
                existingCheckout.id,

              input: {
                userId,
                cartId: cart.id,
                checkoutId:
                  existingCheckout.id,
              },

              output: {
                amount:
                  existingCheckout.amount,

                status:
                  existingCheckout.status,

                policy:
                  existingCheckout.policy,
              },

              status: "SUCCESS",

              reason:
                "Existing active checkout reused",
            });

            return JSON.stringify({
              success: true,

              checkoutCreated:
                false,

              reused: true,

              checkout: {
                id:
                  existingCheckout.id,

                cartId:
                  existingCheckout.cartId,

                amount:
                  existingCheckout.amount,

                currency:
                  existingCheckout.currency,

                status:
                  existingCheckout.status,

                policy:
                  existingCheckout.policy,

                createdAt:
                  existingCheckout.createdAt,

                expiresAt:
                  existingCheckout.expiresAt,
              },

              items,

              policy:
                existingCheckout.policy ||
                policy,

              dailySpent,
            });
          }

          /*
           * Existing checkout is stale because its amount
           * differs from the current authoritative cart.
           *
           * Supersede stale unfinished checkouts for this cart
           * and proceed to create a fresh authoritative checkout.
           */
          await prisma.checkout.updateMany({
            where: {
              cartId: cart.id,
              status: {
                in: [
                  "READY",
                  "AWAITING_APPROVAL",
                  "APPROVED",
                  "PAYMENT_PENDING",
                ],
              },
            },
            data: {
              status: "SUPERSEDED",
            },
          });

          await recordAgentAction({
            agentType: "BUYER_AGENT",
            action: "CHECKOUT_SUPERSEDED",
            entityType: "Checkout",
            entityId: existingCheckout.id,
            input: {
              userId,
              cartId: cart.id,
              existingAmount: existingCheckout.amount,
              currentAmount: totalAmount,
            },
            status: "SUCCESS",
            reason:
              "Existing checkout amount no longer matches current cart; superseded with fresh checkout",
          });
        }

        /*
         * --------------------------------------------------
         * 10. Create the authoritative checkout.
         *
         * IMPORTANT:
         * We persist the complete policy snapshot.
         *
         * checkoutGraph.js will later consume this exact
         * policy instead of recalculating it.
         * --------------------------------------------------
         */
        const checkout =
          await prisma.checkout.create({
            data: {
              cartId:
                cart.id,

              amount:
                totalAmount,

              currency:
                "INR",

              status:
                policy.status ===
                "APPROVAL_REQUIRED"
                  ? "AWAITING_APPROVAL"
                  : "READY",

              policy,
            },
          });

        /*
         * --------------------------------------------------
         * 11. Audit checkout creation.
         * --------------------------------------------------
         */
        await recordAgentAction({
          agentType:
            "BUYER_AGENT",

          action:
            "CHECKOUT_CREATED",

          entityType:
            "Checkout",

          entityId:
            checkout.id,

          input: {
            userId,

            cartId:
              cart.id,

            amount:
              totalAmount,

            policyDecision:
              policy.decision,
          },

          output: {
            checkoutId:
              checkout.id,

            amount:
              checkout.amount,

            currency:
              checkout.currency,

            status:
              checkout.status,

            policy:
              checkout.policy,
          },

          status:
            "SUCCESS",

          reason:
            policy.reason,
        });

        /*
         * --------------------------------------------------
         * 12. Return structured backend-generated state.
         * --------------------------------------------------
         */
        return JSON.stringify({
          success: true,

          checkoutCreated:
            true,

          reused:
            false,

          checkout: {
            id:
              checkout.id,

            cartId:
              checkout.cartId,

            amount:
              checkout.amount,

            currency:
              checkout.currency,

            status:
              checkout.status,

            policy:
              checkout.policy,

            createdAt:
              checkout.createdAt,

            expiresAt:
              checkout.expiresAt,
          },

          items,

          policy,

          dailySpent,
        });
      } catch (error) {
        console.error(
          "create_checkout error:",
          error
        );

        /*
         * Audit unexpected failures.
         */
        try {
          await recordAgentAction({
            agentType:
              "BUYER_AGENT",

            action:
              "CHECKOUT_CREATION_ERROR",

            entityType:
              "Cart",

            input: {
              userId,
            },

            status:
              "FAILED",

            reason:
              error.message ||
              "Unexpected checkout creation error",
          });
        } catch (auditError) {
          console.error(
            "Failed to audit checkout error:",
            auditError
          );
        }

        return JSON.stringify({
          success: false,

          checkoutCreated:
            false,

          error:
            error.message ||
            "Unable to create checkout",
        });
      }
    },

    {
      name:
        "create_checkout",

      description:
        "Create or reuse a secure checkout for the authenticated buyer. Verify cart ownership, validate products and inventory, calculate the authoritative amount from PostgreSQL, calculate real daily spending, evaluate the deterministic policy, persist the complete policy decision on the checkout, and create the checkout.",

      schema: z.object({
        cartId: z
          .string()
          .optional()
          .describe(
            "Optional cart ID. If omitted, the buyer's current active cart is used automatically."
          ),
      }),
    }
  );
}